import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { AIEmergencyAnalyst } from '../AIEmergencyAnalyst';
import { api } from '../../services/api';
import type { SituationReportResponse } from '../../types';

vi.mock('../../services/api', () => ({
  api: {
    getSituationReport: vi.fn(),
  },
}));

const mockReport: SituationReportResponse = {
  simulation_minute: 4,
  generated_at_utc: '2026-10-16T00:00:00Z',
  model_used: 'gemini-2.5-flash',
  advisory_disclaimer: 'ADVISORY DISCLAIMER: This emergency situation report is generated by AI for simulation decision-support.',
  situation_overview: 'Severe flood situation across sector 3 with rising water levels.',
  critical_incidents: [
    {
      incident_id: 'INC001',
      location: 'Zone Northbank-1',
      urgency: 'CRITICAL',
      affected_population: 14,
      waiting_population: 14,
      reason: 'Isolated patients stranded in flood zone.',
    },
  ],
  resource_status: {
    total_boats: 4,
    available_boats: 3,
    dispatched_boats: 1,
    failed_boats: 0,
    total_shelter_capacity: 100,
    shelter_current_occupancy: 20,
    shelter_remaining_capacity: 80,
    shortages_and_notes: 'Adequate capacity available.',
  },
  bottlenecks_and_risks: [
    {
      category: 'Road Blockage',
      description: 'Bridge N2 is submerged.',
      severity: 'high',
      evidence: 'Edge N2 closure verified.',
    },
  ],
  recommended_actions: [
    {
      action_id: 'ACT-1',
      title: 'Prioritize INC001 Evacuation',
      rationale: 'Critical stranded group in rapidly rising water.',
      priority: 'critical',
      target_entity: 'BOAT01',
      advisory_note: 'Advisory suggestion for human operator review only.',
    },
  ],
  strategy_performance: {
    current_strategy: 'centralized',
    measurements_available: false,
    summary: 'Centralized greedy baseline active in session.',
  },
  data_limitations: {
    has_limitations: true,
    limitations: ['Synthetic simulation environment.', 'Live sensors not connected.'],
  },
};

describe('AIEmergencyAnalyst Frontend Component', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('renders initial empty state with "Generate AI Situation Report" button', () => {
    render(<AIEmergencyAnalyst currentMinute={4} activeStrategy="centralized" />);

    expect(screen.getByText('AI Emergency Situation Analyst')).toBeTruthy();
    expect(screen.getByText(/Google Gemini 2.5/i)).toBeTruthy();
    const generateBtn = screen.getByRole('button', { name: /Generate AI Situation Report/i });
    expect(generateBtn).toBeTruthy();
  });

  it('shows loading indicator and disables button while request is in progress to prevent duplicate clicks', async () => {
    let resolvePromise: (value: any) => void;
    const pendingPromise = new Promise((resolve) => {
      resolvePromise = resolve;
    });

    vi.mocked(api.getSituationReport).mockReturnValue(pendingPromise as any);

    render(<AIEmergencyAnalyst currentMinute={4} activeStrategy="centralized" />);

    const generateBtn = screen.getByRole('button', { name: /Generate AI Situation Report/i });
    fireEvent.click(generateBtn);

    // Verify loading indicator is displayed
    expect(screen.getByText(/Gemini AI is analyzing snapshot at Minute T\+4/i)).toBeTruthy();
    expect(generateBtn.getAttribute('disabled')).not.toBeNull();

    // Resolve promise
    resolvePromise!(mockReport);
    await waitFor(() => {
      expect(screen.queryByText(/Gemini AI is analyzing snapshot at Minute T\+4/i)).toBeNull();
    });
  });

  it('displays the structured situation report sections upon successful response', async () => {
    vi.mocked(api.getSituationReport).mockResolvedValue(mockReport);

    render(<AIEmergencyAnalyst currentMinute={4} activeStrategy="centralized" />);

    const generateBtn = screen.getByRole('button', { name: /Generate AI Situation Report/i });
    fireEvent.click(generateBtn);

    await waitFor(() => {
      expect(screen.getByText(/1\. Situation Overview/i)).toBeTruthy();
      expect(screen.getByText(mockReport.situation_overview)).toBeTruthy();
      expect(screen.getByText(/2\. Critical Incidents/i)).toBeTruthy();
      expect(screen.getByText('INC001')).toBeTruthy();
      expect(screen.getByText(/3\. Fleet & Shelter Resources/i)).toBeTruthy();
      expect(screen.getByText(/4\. Bottlenecks & Operational Risks/i)).toBeTruthy();
      expect(screen.getByText(/5\. Recommended Practical Actions/i)).toBeTruthy();
      expect(screen.getByText('ACT-1')).toBeTruthy();
      expect(screen.getByText(/Prioritize INC001 Evacuation/i)).toBeTruthy();
      expect(screen.getByText(/6\. Strategy Performance Assessment/i)).toBeTruthy();
      expect(screen.getByText(/7\. Data Limitations & Scope/i)).toBeTruthy();
      expect(screen.getByText(/Simulation Advisory Only:/i)).toBeTruthy();
    });
  });

  it('displays helpful error message when API call fails or API key is missing', async () => {
    vi.mocked(api.getSituationReport).mockRejectedValue(
      new Error('GEMINI_API_KEY environment variable is not configured on the backend.')
    );

    render(<AIEmergencyAnalyst currentMinute={4} activeStrategy="centralized" />);

    const generateBtn = screen.getByRole('button', { name: /Generate AI Situation Report/i });
    fireEvent.click(generateBtn);

    await waitFor(() => {
      expect(screen.getByText(/Situation Report Generation Error/i)).toBeTruthy();
      expect(
        screen.getByText(/GEMINI_API_KEY environment variable is not configured on the backend\./i)
      ).toBeTruthy();
      expect(screen.getByText(/Configuration Guide:/i)).toBeTruthy();
    });
  });

  it('indicates stale snapshot when simulation minute advances', async () => {
    vi.mocked(api.getSituationReport).mockResolvedValue(mockReport);

    const { rerender } = render(<AIEmergencyAnalyst currentMinute={4} activeStrategy="centralized" />);

    const generateBtn = screen.getByRole('button', { name: /Generate AI Situation Report/i });
    fireEvent.click(generateBtn);

    await waitFor(() => {
      expect(screen.getByText(/Snapshot: T\+4m \(Current\)/i)).toBeTruthy();
    });

    // Advance clock to minute 6
    rerender(<AIEmergencyAnalyst currentMinute={6} activeStrategy="centralized" />);

    await waitFor(() => {
      expect(screen.getByText(/Snapshot: T\+4m \(Live: T\+6m\)/i)).toBeTruthy();
      expect(screen.getByText(/Re-analyze at T\+6m/i)).toBeTruthy();
    });
  });
});
