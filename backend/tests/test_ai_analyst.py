@patch("backend.app.services.ai_analyst.genai.Client")
def test_simulation_state_immutability(mock_genai_client, monkeypatch):
    """
    CRITICAL SAFETY REQUIREMENT:
    Generating an AI Situation Report must NEVER modify the simulation state,
    advance the clock, alter boat coordinates, mutate incident lifecycle,
    or override existing assignments.
    """
    monkeypatch.setenv("GEMINI_API_KEY", "test-mock-api-key")
    session_manager.reset(strategy="centralized")

    # Step simulation to minute 3 to have ongoing assignments
    session_manager.step()
    session_manager.step()
    session_manager.step()

    # Capture state before report
    state_before = session_manager.get_state()
    minute_before = state_before.minute
    boats_before = [b.model_dump() for b in state_before.boats]
    incidents_before = [i.model_dump() for i in state_before.incidents]
    assignments_before = [a.model_dump() for a in state_before.active_assignments]

    mock_instance = MagicMock()
    mock_response = MagicMock()
    mock_response.text = MOCK_VALID_REPORT_JSON
    mock_instance.models.generate_content.return_value = mock_response
    mock_genai_client.return_value = mock_instance

    # Call AI report endpoint
    response = client.post("/api/ai/situation-report")
    assert response.status_code == 200
    report_data = response.json()

    # Verify report snapshot aligns with minute 3
    assert report_data["simulation_minute"] == minute_before

    # Capture state after report
    state_after = session_manager.get_state()
    minute_after = state_after.minute
    boats_after = [b.model_dump() for b in state_after.boats]
    incidents_after = [i.model_dump() for i in state_after.incidents]
    assignments_after = [a.model_dump() for a in state_after.active_assignments]

    # Strictly assert immutability
    assert minute_after == minute_before
    assert boats_after == boats_before
    assert incidents_after == incidents_before
    assert assignments_after == assignments_before


