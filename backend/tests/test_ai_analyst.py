def test_missing_api_key_returns_503(monkeypatch):
    """When GEMINI_API_KEY is not configured or empty, endpoint returns HTTP 503."""
    monkeypatch.setenv("GEMINI_API_KEY", "")
    session_manager.reset(strategy="centralized")

    response = client.post("/api/ai/situation-report")
    assert response.status_code == 503
    data = response.json()
    assert "GEMINI_API_KEY" in data["detail"]
    assert "not configured" in data["detail"]


